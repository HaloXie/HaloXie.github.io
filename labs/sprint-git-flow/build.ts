import { readFile, writeFile } from 'node:fs/promises';
import { stripTypeScriptTypes } from 'node:module';

const controls = await readFile(new URL('../shared/antd-controls.ts', import.meta.url), 'utf8');
await writeFile(new URL('../shared/antd-controls.mjs', import.meta.url), stripTypeScriptTypes(controls).replace(/^[\t ]+$/gm, ''));

for (const name of ['model', 'locale', 'app']) {
  const source = await readFile(new URL(`./${name}.ts`, import.meta.url), 'utf8');
  const compiled = stripTypeScriptTypes(source).replaceAll(/'\.\/(model|locale)\.ts'/g, "'./$1.mjs'").replace(/^[\t ]+$/gm, '');
  await writeFile(new URL(`./${name}.mjs`, import.meta.url), `// Generated by node labs/sprint-git-flow/build.ts; edit ${name}.ts.\n${compiled}`);
}
